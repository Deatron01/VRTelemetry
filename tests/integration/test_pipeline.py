import os
import time
import pytest
from pathlib import Path

from src.core.engine import TelemetryEngine
from src.backends.discovery import RuntimeCapabilityDiscovery
from src.core.exceptions import GDPRConsentError

@pytest.fixture
def temp_session_dir(tmp_path: Path) -> str:
    """Provides an isolated temporary directory for integration test outputs."""
    session_dir = tmp_path / "IntegrationSessions"
    session_dir.mkdir()
    return str(session_dir)

def test_engine_initialization_without_consent(temp_session_dir: str):
    """
    Validates Requirement 2.50: The system must hard-crash and refuse to boot
    if explicit GDPR biometric tracking consent is not provided.
    """
    with pytest.raises(GDPRConsentError, match="Explicit user GDPR consent missing"):
        TelemetryEngine(output_dir=temp_session_dir, gdpr_consent=False)

def test_headless_pipeline_execution(temp_session_dir: str):
    """
    End-to-End integration test simulating a brief recording session.
    Bootstraps the headless OpenXR layer, executes the biometric synchronizer,
    and flushes synthetic frames to the Parquet binary matrix.
    """
    # 1. Discover static capabilities
    hardware_metadata = RuntimeCapabilityDiscovery.extract_static_hardware_metadata()
    
    # 2. Boot Engine with explicit consent
    engine = TelemetryEngine(
        output_dir=temp_session_dir,
        gdpr_consent=True,
        hardware_metadata=hardware_metadata,
        subject_metadata={
            "M-IV_Static_Metadata": {"session_id": "TEST_SESSION_01", "subject_id": "UNIT_TEST"},
            "C-V_Calibration": {},
            "Q-VI_Subjective_Labels": {},
            "H-VII_Hardware_Capabilities": hardware_metadata
        }
    )
    
    # Overwrite the parquet writer's flush interval to force a disk write immediately
    engine.writer.flush_interval = 10 
    
    # 3. Simulate runtime engine loop asynchronously via threading to allow intervention
    import threading
    
    def run_engine_stub():
        engine.is_running = True
        engine._start_async_loop()
        
    engine_thread = threading.Thread(target=run_engine_stub, daemon=True)
    engine_thread.start()
    
    try:
        # Give async loops time to bind
        time.sleep(0.5)
        
        # Manually pump frames bypassing the OpenXR blocking hardware call for the test
        for i in range(15):
            frame = engine.backend.poll_frame(i)
            engine.synchronizer.push_frame(frame)
            engine.frames_recorded += 1
            
        time.sleep(0.5) # Wait for async writer queue to process
        
    finally:
        engine._teardown()
        engine_thread.join(timeout=2.0)
        
    # 4. Assertions verifying disk and structural integrity
    parquet_files = list(Path(temp_session_dir).glob("*.parquet"))
    assert len(parquet_files) == 1, "Parquet matrix file was not generated by the asynchronous writer."
    
    # Verify file is populated (size > minimal header)
    file_size = os.path.getsize(parquet_files[0])
    assert file_size > 1000, "Parquet matrix appears empty or unwritten."