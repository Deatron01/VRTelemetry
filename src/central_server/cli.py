"""``vrtelemetry-hub``: the one executable an installed hub has.

A hub installed from the Windows installer has no Python, so everything the
README's hub setup does by hand -- serve, create the TLS certificate, create
the first administrator -- has to be reachable from the frozen executable. One
program with subcommands rather than three, because PyInstaller would otherwise
ship three copies of the same runtime.

``setup`` is what the installer runs. It is idempotent and never overwrites a
lab's own choices: ``config.toml`` and the certificate are written only when
missing, so reinstalling or upgrading keeps them. Only the workstation kit is
rewritten each time, because it is derived from the other two.

The data root is chosen before anything reads settings. ``get_settings()`` reads
``config.toml`` from the working directory and caches the result, so
``--data-root`` changes directory first and imports the rest of the hub only
afterwards.
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path
from xml.sax.saxutils import escape

from src.config.workstation_kit import workstation_config_toml
from src.utils.clock import utc_now

#: Where an installed hub keeps its data when nothing says otherwise. Never the
#: install directory: that is replaced on upgrade and read-only to services.
FROZEN_DEFAULT_DATA_ROOT = Path(os.environ.get("PROGRAMDATA", r"C:\ProgramData")) / "VRTelemetryHub"

KIT_DIR_NAME = "workstation-kit"

_KIT_README = """\
VRTelemetry workstation kit
===========================

Generated by the hub at {url} on {date}.

Easiest: pair instead of copying. In the admin UI ({url}/admin-ui/), open
"Pair a Workstation" and generate a code; in the desktop app, choose "Connect
to a hub on another machine" and enter {url} and the code.

To set up a recording PC by hand instead, after installing VRTelemetry:

1. Close the VRTelemetry desktop app.
2. Copy hub-ca.pem and config.toml from this folder into
       %APPDATA%\\VRTelemetry\\data
   (create the folder if the app has never been started). If that folder
   already has a config.toml, copy the [central] block into it instead.
3. Start the app, log in or register, and activate with a licence key
   issued in the admin UI: {url}/admin-ui/

hub-ca.pem is public: it lets the workstation verify it is talking to this
hub. Never copy hub-ca-key.pem or hub-key.pem off the hub machine.
"""


def _default_data_root() -> Path:
    if os.environ.get("VRT_PATHS__DATA_ROOT"):
        return Path(os.environ["VRT_PATHS__DATA_ROOT"])
    if getattr(sys, "frozen", False):
        return FROZEN_DEFAULT_DATA_ROOT
    return Path.cwd()


def _enter_data_root(data_root: Path) -> Path:
    data_root = data_root.expanduser().resolve()
    data_root.mkdir(parents=True, exist_ok=True)
    os.chdir(data_root)
    os.environ["VRT_PATHS__DATA_ROOT"] = str(data_root)
    return data_root


def hub_config_toml(port: int, tls_dir: Path) -> str:
    """The hub's ``config.toml`` as the installer first writes it."""
    return (
        f"# Written by the VRTelemetry Hub installer on {utc_now().date().isoformat()}.\n"
        "# Edit freely: reinstalling or upgrading keeps this file.\n"
        "# Every option is described in config.example.toml in the source repository.\n"
        "\n"
        "[hub]\n"
        'host = "0.0.0.0"\n'
        f"port = {port}\n"
        f'tls_certfile = "{(tls_dir / "hub-cert.pem").as_posix()}"\n'
        f'tls_keyfile = "{(tls_dir / "hub-key.pem").as_posix()}"\n'
    )


def write_workstation_kit(kit_dir: Path, url: str, ca_file: Path) -> Path:
    """The folder an administrator copies to a workstation by hand.

    The file format is :mod:`src.config.workstation_kit`'s, shared with pairing,
    which writes the same two files on the workstation without the copying.
    """
    kit_dir.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ca_file, kit_dir / "hub-ca.pem")
    (kit_dir / "config.toml").write_text(workstation_config_toml(url), encoding="utf-8")
    (kit_dir / "README.txt").write_text(
        _KIT_README.format(url=url, date=utc_now().date().isoformat()), encoding="utf-8"
    )
    return kit_dir


TASK_XML_NAME = "hub-task.xml"


def task_xml(exe: Path, data_root: Path) -> str:
    """The Task Scheduler definition that keeps the hub running.

    A scheduled task rather than a Windows service: a service needs a wrapper
    binary (WinSW, NSSM) between the SCM and a console program, and this needs
    nothing the task lacks -- start at boot as SYSTEM, no time limit, restart
    after a crash. Written here rather than in the NSIS script so it is tested,
    and in UTF-16 by the caller because that is what ``schtasks /XML`` reads.
    """
    command = escape(str(exe))
    arguments = escape(f'--data-root "{data_root}" serve')
    workdir = escape(str(data_root))
    return f"""<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>VRTelemetry central hub. Installed by the VRTelemetry Hub installer.</Description>
  </RegistrationInfo>
  <Triggers>
    <BootTrigger>
      <Enabled>true</Enabled>
    </BootTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>S-1-5-18</UserId>
      <RunLevel>HighestAvailable</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure>
      <Interval>PT1M</Interval>
      <Count>999</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{command}</Command>
      <Arguments>{arguments}</Arguments>
      <WorkingDirectory>{workdir}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
"""


def create_admin() -> int:
    """``bootstrap-admin`` for someone who opened it from the Start menu.

    The installer cannot ask for the administrator's password -- it would sit
    in the installer's memory and log -- so the Start-menu entry runs this in a
    console instead. It prompts for what ``bootstrap-admin`` takes as flags and
    keeps the window open long enough to read the result.
    """
    from src.license_service import bootstrap_admin

    print("Create the first VRTelemetry hub administrator.\n")
    email = input("Email: ").strip()
    org = input("Organisation (e.g. the lab's name): ").strip()
    code = 2
    if email:
        code = bootstrap_admin.main(["--email", email, "--org", org])
    else:
        print("No email given; nothing was changed.")
    input("\nPress Enter to close this window.")
    return code


def setup(data_root: Path, addresses: list[str], port: int) -> int:
    """Prepare a hub data root: config, certificate, workstation kit, task."""
    from src.central_server import certificates

    tls_dir = data_root / "CentralServer" / "tls"
    config_path = data_root / "config.toml"

    if config_path.exists():
        print(f"Keeping existing {config_path}")
    else:
        config_path.write_text(hub_config_toml(port, tls_dir), encoding="utf-8")
        print(f"Wrote {config_path}")

    if (tls_dir / "hub-key.pem").exists():
        print(f"Keeping existing certificate in {tls_dir}")
    else:
        certificates.generate(addresses, tls_dir)
        print(f"Created a certificate for {', '.join(addresses)} in {tls_dir}")

    url = f"https://{addresses[0]}:{port}"
    kit = write_workstation_kit(data_root / KIT_DIR_NAME, url, tls_dir / "hub-ca.pem")
    print(f"Workstation kit for {url}: {kit}")

    # Rewritten every time: it names the executable, which moves if the hub is
    # reinstalled to another directory.
    exe = Path(sys.executable) if getattr(sys, "frozen", False) else Path(sys.argv[0]).resolve()
    (data_root / TASK_XML_NAME).write_text(task_xml(exe, data_root), encoding="utf-16")
    return 0


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="vrtelemetry-hub",
        description="VRTelemetry central hub. With no command, serves.",
    )
    parser.add_argument(
        "--data-root",
        type=Path,
        default=None,
        help="Directory holding config.toml and the hub's databases "
        "(default: VRT_PATHS__DATA_ROOT, else %%ProgramData%%\\VRTelemetryHub when installed, "
        "else the current directory).",
    )
    commands = parser.add_subparsers(dest="command")
    commands.add_parser("serve", help="Run the hub (the default).")
    commands.add_parser(
        "gen-cert", help="Create a TLS certificate for the hub's LAN address.", add_help=False
    )
    commands.add_parser(
        "bootstrap-admin", help="Create or promote the first administrator.", add_help=False
    )
    commands.add_parser(
        "create-admin", help="Interactive bootstrap-admin, for the Start-menu entry."
    )
    setup_parser = commands.add_parser(
        "setup", help="Write config, certificate and workstation kit if missing (installer)."
    )
    setup_parser.add_argument(
        "--address",
        action="append",
        required=True,
        help="LAN address workstations use to reach the hub (repeatable; the first goes "
        "into the workstation kit).",
    )
    setup_parser.add_argument("--port", type=int, default=9000)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args, rest = parser.parse_known_args(sys.argv[1:] if argv is None else argv)
    if rest and args.command not in ("gen-cert", "bootstrap-admin"):
        parser.error(f"unrecognised arguments: {' '.join(rest)}")

    data_root = _enter_data_root(args.data_root or _default_data_root())

    if args.command == "gen-cert":
        from src.central_server import certificates

        return certificates.main(rest)
    if args.command == "bootstrap-admin":
        from src.license_service import bootstrap_admin

        return bootstrap_admin.main(rest)
    if args.command == "create-admin":
        return create_admin()
    if args.command == "setup":
        return setup(data_root, args.address, args.port)

    from src.central_server import server

    server.main()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
