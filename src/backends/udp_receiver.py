# src/backends/udp_receiver.py

import asyncio
import logging
import struct
import time

from src.config import get_settings
from src.core.datatypes import TelemetryFrame
from src.core.synchronizer import BiometricSynchronizer

logger = logging.getLogger(__name__)


class NativeQuestHarvesterProtocol(asyncio.DatagramProtocol):
    """
    High-performance UDP ingestion protocol.
    Catches 64-byte unmanaged binary structs generated by the Quest Pro native overlay.
    """

    # Struct Format:
    # <  = Little-endian
    # I  = FrameIndex (4 bytes)
    # 3f = LeftPos (12 bytes)
    # 4f = LeftRot (16 bytes)
    # 3f = RightPos (12 bytes)
    # 4f = RightRot (16 bytes)
    # H  = LeftConfidence (2 bytes)
    # H  = RightConfidence (2 bytes)
    # Total: 64 bytes
    STRUCT_SIG = "<I 3f 4f 3f 4f H H"
    PAYLOAD_SIZE = 64

    def __init__(self, synchronizer: BiometricSynchronizer):
        self.synchronizer = synchronizer
        self.transport: asyncio.DatagramTransport | None = None
        self.unpack = struct.Struct(self.STRUCT_SIG).unpack

    def connection_made(self, transport: asyncio.DatagramTransport) -> None:
        self.transport = transport
        logger.info("Native Quest UDP socket bound. Awaiting biometric payloads...")

    def datagram_received(self, data: bytes, addr: tuple[str, int]) -> None:
        if len(data) != self.PAYLOAD_SIZE:
            logger.debug(f"Discarded malformed packet from {addr} (Size: {len(data)})")
            return

        try:
            # Native C-level unpacking is roughly ~50x faster than json.loads()
            unpacked = self.unpack(data)

            # Map into the standard TelemetryFrame format for downstream Parquet ingestion
            frame = TelemetryFrame.create_empty(unpacked[0])
            frame.timestamp_ns = time.time_ns()

            # Left Eye
            frame.left_eye_pos_x, frame.left_eye_pos_y, frame.left_eye_pos_z = unpacked[1:4]
            (
                frame.left_eye_rot_x,
                frame.left_eye_rot_y,
                frame.left_eye_rot_z,
                frame.left_eye_rot_w,
            ) = unpacked[4:8]

            # Right Eye
            frame.right_eye_pos_x, frame.right_eye_pos_y, frame.right_eye_pos_z = unpacked[8:11]
            (
                frame.right_eye_rot_x,
                frame.right_eye_rot_y,
                frame.right_eye_rot_z,
                frame.right_eye_rot_w,
            ) = unpacked[11:15]

            # Reverse the ushort confidence mapping (0-65535 back to 0.0-1.0)
            left_conf = unpacked[15] / 65535.0
            right_conf = unpacked[16] / 65535.0

            # Use pupil fields for confidence logging, mark validation true if tracking is locked
            frame.left_pupil_size = left_conf
            frame.right_pupil_size = right_conf
            frame.eye_tracking_valid = 1.0 if (left_conf > 0.5 and right_conf > 0.5) else 0.0

            # Push instantly to the lock-free queue
            self.synchronizer.push_frame(frame)

        except Exception as e:
            logger.error(f"UDP Deserialization fault: {e}")


class NativeQuestReceiver:
    """Orchestrator for the background UDP ingestion service."""

    def __init__(self, host: str | None = None, port: int | None = None):
        settings = get_settings().acquisition
        self.host = host or settings.udp_host
        self.port = port or settings.udp_port
        self.transport = None

    async def start(self, synchronizer: BiometricSynchronizer) -> None:
        loop = asyncio.get_running_loop()

        logger.info(f"Binding Native UDP Harvester on {self.host}:{self.port}")
        self.transport, _ = await loop.create_datagram_endpoint(
            lambda: NativeQuestHarvesterProtocol(synchronizer), local_addr=(self.host, self.port)
        )

    def stop(self) -> None:
        if self.transport:
            self.transport.close()
            logger.info("Native Quest UDP socket closed safely.")
